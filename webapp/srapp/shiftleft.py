"""Shift-left: 1-click pull request that adds a performance gate to an application repository.

The gate runs on a Bitbucket self-hosted *Linux shell* runner installed on the JMeter Master
(the Control Center listens on 127.0.0.1 only), calls the Control Center API with a CI token,
waits for the run and fails the pipeline when the SLA (p95 / error %) is not met.
"""
import time

from . import atlassian, projects, settings

FILES_DIR = "perf"


def _cfg(project):
    s = settings.project(project)
    sl = s["shiftleft"]
    if not sl.get("tag"):
        raise ValueError("Choose the tag to run in the Shift-left settings first")
    t = projects.get_tag(project, sl["tag"])
    if not t or not t["exists"]:
        raise ValueError(f"Tag {sl['tag']} does not exist in {project}")
    return s, sl


def generate(project):
    s, sl = _cfg(project)
    label = sl.get("runner_label") or "jmeter-master"
    gate = f'''#!/usr/bin/env bash
# ------------------------------------------------------------------------------
# Performance gate — generated by JMeter Control Center for {project}
# Runs on the Bitbucket self-hosted runner installed on the JMeter Master.
# Repository variables (Repository settings → Pipelines → Repository variables):
#   JMCC_TOKEN  (secured)  CI token from Control Center → Account → API tokens (role operator)
#   JMCC_JIRA   (optional) Jira ticket to comment, e.g. PERF-123
# ------------------------------------------------------------------------------
set -euo pipefail
JMCC_URL="${{JMCC_URL:-http://127.0.0.1:8090}}"
: "${{JMCC_TOKEN:?Define JMCC_TOKEN as a secured repository variable}}"
PROJECT="${{JMCC_PROJECT:-{project}}}"
TAG="${{JMCC_TAG:-{sl['tag']}}}"
THREADS="${{JMCC_THREADS:-{int(sl.get('threads') or 5)}}}"
DURATION="${{JMCC_DURATION:-{int(sl.get('duration') or 120)}}}"
SLA_P95="${{JMCC_SLA_P95:-{float(sl.get('sla_p95') or 1500):g}}}"
SLA_ERR="${{JMCC_SLA_ERR:-{float(sl.get('sla_err') or 1):g}}}"
NOTES="Bitbucket ${{BITBUCKET_REPO_SLUG:-local}} build #${{BITBUCKET_BUILD_NUMBER:-0}} commit ${{BITBUCKET_COMMIT:-n/a}}"

payload=$(python3 - "$PROJECT" "$TAG" "$THREADS" "$DURATION" "${{JMCC_JIRA:-}}" "$NOTES" <<'PY'
import json, sys
p, tag, thr, dur, jira, notes = sys.argv[1:7]
print(json.dumps({{"project": p, "tag": tag, "props": f"-Jthreads={{thr}} -Jduration={{dur}}",
                  "distributed": False, "jira": jira, "notes": notes}}))
PY
)
echo "==> Starting $TAG ($THREADS users, $DURATION s) on the JMeter Control Center"
resp=$(curl -fsS -X POST "$JMCC_URL/api/v1/runs" -H "Authorization: Bearer $JMCC_TOKEN" \\
       -H "Content-Type: application/json" -d "$payload")
RUN_ID=$(python3 -c 'import json,sys; print(json.load(sys.stdin)["id"])' <<<"$resp")
echo "==> Run $RUN_ID  ($JMCC_URL/runs/$RUN_ID)"

while true; do
  sleep 15
  st=$(curl -fsS "$JMCC_URL/api/v1/runs/$RUN_ID?sla_p95=$SLA_P95&sla_err=$SLA_ERR" -H "Authorization: Bearer $JMCC_TOKEN")
  status=$(python3 -c 'import json,sys; print(json.load(sys.stdin)["status"])' <<<"$st")
  case "$status" in starting|running|stopping) echo "    ... $status"; continue ;; esac
  break
done

SUMMARY_PY='
import json, sys
d = json.load(sys.stdin)
t = d.get("summary") or {{}}
print("==> Status: %s   report: %s" % (d["status"], d.get("report_url") or "-"))
if t:
    print("    samples=%s  error=%s%%  avg=%sms  p95=%sms  tps=%s" % (t.get("samples"), t.get("error_pct"),
          round(t.get("avg") or 0), round(t.get("p95") or 0), t.get("tps")))
for c in d.get("sla", {{}}).get("checks", []):
    print("    [%s] %s: %s (limit %s)" % ("OK" if c["ok"] else "FAIL", c["name"], c["actual"], c["limit"]))
'
python3 -c "$SUMMARY_PY" <<<"$st"

passed=$(python3 -c 'import json,sys; d=json.load(sys.stdin); print("yes" if d["status"]=="finished" and d.get("sla",{{}}).get("passed") else "no")' <<<"$st")
if [ "$passed" != "yes" ]; then
  echo "==> PERFORMANCE GATE FAILED"; exit 1
fi
echo "==> Performance gate passed"
'''
    step = f'''      - step:
          name: Performance gate (JMeter Control Center)
          runs-on:
            - self.hosted
            - linux.shell
            - {label}
          max-time: 60
          script:
            - bash {FILES_DIR}/perf-gate.sh
'''
    pipelines = f'''# Generated by JMeter Control Center — custom pipeline, trigger it from Pipelines → Run pipeline
# (or add the step to your deployment pipeline right after the deploy to QA).
pipelines:
  custom:
    performance-gate:
{step}'''
    readme = f'''# Performance gate (shift-left)

Generated by **JMeter Control Center** for `{project}` · tag `{sl['tag']}`.

| Setting | Value |
|---------|-------|
| Users / duration | {sl.get('threads')} users · {sl.get('duration')} s |
| SLA | p95 ≤ {sl.get('sla_p95')} ms · error ≤ {sl.get('sla_err')} % |
| Runner labels | `self.hosted`, `linux.shell`, `{label}` |

## One-time setup
1. **Runner** — Repository settings → Runners → *Add runner* → Linux Shell, label `{label}`, and run the
   given command **on the JMeter Master** (the Control Center only listens on `127.0.0.1`).
2. **Token** — Control Center → *Account → API tokens* → create a token for a user with role *operator*;
   add it as a **secured** repository variable `JMCC_TOKEN`. Optional: `JMCC_JIRA` with a ticket key.
3. Merge this PR. Trigger *Run pipeline → custom: performance-gate*, or paste the step from
   `{FILES_DIR}/bitbucket-pipelines.snippet.yml` after your deploy-to-QA step.

The step fails when the run fails or the SLA is not met; the HTML report, Grafana link, e-mail
notification and Jira comment are produced by the Control Center as for any other run.
'''
    return {f"{FILES_DIR}/perf-gate.sh": gate, f"{FILES_DIR}/README.md": readme,
            f"{FILES_DIR}/bitbucket-pipelines.snippet.yml": step, "_pipelines": pipelines}


def open_pull_request(username, project):
    s, sl = _cfg(project)
    repo = s.get("bitbucket_repo")
    if not atlassian.REPO_RE.match(repo or ""):
        raise ValueError("Set the application repository as <workspace>/<repo-slug> first")
    bb = atlassian.Bitbucket(username)
    info = bb.repo(repo)
    base = sl.get("base_branch") or info["main"]
    files = generate(project)
    pipelines = files.pop("_pipelines")
    created_pipelines = False
    if not bb.file_exists(repo, base, "bitbucket-pipelines.yml"):
        files["bitbucket-pipelines.yml"] = pipelines
        created_pipelines = True
    branch = f"perf/performance-gate-{time.strftime('%Y%m%d%H%M%S')}"
    bb.commit_files(repo, branch, base, f"Add JMeter performance gate ({sl['tag']})", files)
    desc = (f"Adds a **performance gate** that runs `{sl['tag']}` from `{project}` on the JMeter generators "
            f"and fails when p95 > {sl.get('sla_p95')} ms or errors > {sl.get('sla_err')} %.\n\n"
            + ("A `bitbucket-pipelines.yml` with a custom `performance-gate` pipeline is included.\n\n"
               if created_pipelines else
               "This repository already has `bitbucket-pipelines.yml`: **add the step from "
               "`perf/bitbucket-pipelines.snippet.yml`** to it in this PR (after the deploy to QA).\n\n")
            + "See `perf/README.md` for the one-time runner + token setup.\n\n_Opened from JMeter Control Center._")
    url = bb.pull_request(repo, branch, base, f"Performance gate: {sl['tag']}", desc)
    return url, created_pipelines
